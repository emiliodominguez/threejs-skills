#!/usr/bin/env node
// Finds and downloads 3D assets with their license recorded: Poly Haven (CC0 models, HDRIs, textures;
// no key) and Sketchfab (search is public; downloads need SKETCHFAB_TOKEN). Every download appends
// to CREDITS.json and regenerates CREDITS.md in the output folder, so attribution is never lost.
//
//   node fetch.mjs search polyhaven chair                       # models (default), --type hdris|textures
//   node fetch.mjs search sketchfab "office chair" --license cc0 --max-faces 50000
//   node fetch.mjs download polyhaven ArmChair_01 --res 1k --out public/models
//   node fetch.mjs download polyhaven studio_small_03 --type hdris --res 2k --out public/hdr
//   SKETCHFAB_TOKEN=... node fetch.mjs download sketchfab 9c7f1f712edc4b3196e8dcca39a9a537 --out public/models

import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const USER_AGENT = "threejs-skills/0.1 (+https://github.com/emiliodominguez/threejs-skills)";
const POLY_HAVEN = "https://api.polyhaven.com";
const SKETCHFAB = "https://api.sketchfab.com/v3";
const TYPES = { models: "models", hdris: "hdris", textures: "textures" };

/**
 * Fetches JSON with the skill's user agent.
 * @param {string} url
 * @param {Record<string, string>} [headers]
 * @returns {Promise<any>}
 */
async function getJson(url, headers = {}) {
	const response = await fetch(url, { headers: { "user-agent": USER_AGENT, ...headers } });
	if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
	return response.json();
}

/**
 * Downloads a URL to a file, creating folders.
 * @param {string} url
 * @param {string} path
 * @returns {Promise<number>} bytes written
 */
async function download(url, path) {
	const response = await fetch(url, { headers: { "user-agent": USER_AGENT } });
	if (!response.ok) throw new Error(`${response.status} downloading ${url}`);
	const bytes = Buffer.from(await response.arrayBuffer());
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, bytes);
	return bytes.length;
}

/**
 * Appends a credit and rewrites CREDITS.md in the output folder.
 * @param {string} outDir
 * @param {{ name: string, file: string, source: string, url: string, author: string, license: string, licenseUrl: string, attributionRequired: boolean }} credit
 */
export function recordCredit(outDir, credit) {
	const jsonPath = join(outDir, "CREDITS.json");
	const credits = existsSync(jsonPath) ? JSON.parse(readFileSync(jsonPath, "utf8")) : [];
	const entry = { ...credit, downloaded: new Date().toISOString().slice(0, 10) };
	const index = credits.findIndex((existing) => existing.file === credit.file);
	if (index >= 0) credits[index] = entry;
	else credits.push(entry);
	writeFileSync(jsonPath, `${JSON.stringify(credits, null, "\t")}\n`);
	const lines = ["# Asset credits", "", "Generated by the threejs-assets fetch script. Keep this file with the assets.", ""];
	for (const item of credits) {
		lines.push(`- **${item.name}** (\`${item.file}\`) by ${item.author}, from [${item.source}](${item.url}), licensed [${item.license}](${item.licenseUrl})${item.attributionRequired ? ". Attribution required." : "."}`);
	}
	writeFileSync(join(outDir, "CREDITS.md"), `${lines.join("\n")}\n`);
}

/**
 * Searches Poly Haven by name, tags and categories (the API lists assets; matching happens here).
 * @param {string} query
 * @param {string} type
 * @returns {Promise<{ id: string, name: string, detail: string }[]>}
 */
async function searchPolyHaven(query, type) {
	const assets = await getJson(`${POLY_HAVEN}/assets?t=${TYPES[type]}`);
	const words = query.toLowerCase().split(/\s+/).filter(Boolean);
	return Object.entries(assets)
		.filter(([id, asset]) => {
			const haystack = [id, asset.name, ...(asset.tags ?? []), ...(asset.categories ?? [])].join(" ").toLowerCase();
			return words.every((word) => haystack.includes(word));
		})
		.sort((a, b) => (b[1].download_count ?? 0) - (a[1].download_count ?? 0))
		.slice(0, 20)
		.map(([id, asset]) => ({
			id,
			name: asset.name,
			detail: [asset.polycount ? `${asset.polycount.toLocaleString("en-US")} polys` : null, asset.max_resolution ? `up to ${asset.max_resolution[0]}px` : null, "CC0"].filter(Boolean).join(", "),
		}));
}

/**
 * Searches downloadable Sketchfab models.
 * @param {string} query
 * @param {{ license?: string, maxFaces?: number }} options
 * @returns {Promise<{ id: string, name: string, detail: string }[]>}
 */
async function searchSketchfab(query, options) {
	const params = new URLSearchParams({ type: "models", downloadable: "true", q: query, count: "20" });
	if (options.license) params.set("license", options.license);
	if (options.maxFaces) params.set("max_face_count", String(options.maxFaces));
	const { results } = await getJson(`${SKETCHFAB}/search?${params}`);
	return results.map((model) => ({
		id: model.uid,
		name: model.name,
		detail: `${model.faceCount?.toLocaleString("en-US") ?? "?"} faces, ${model.animationCount ? `${model.animationCount} animations, ` : ""}${model.license?.label ?? "license ?"}, by ${model.user?.username}`,
	}));
}

/**
 * Downloads a Poly Haven asset at a resolution and records its CC0 credit.
 * @param {string} id
 * @param {{ type: string, res: string, outDir: string }} options
 * @returns {Promise<string>} main file path
 */
async function downloadPolyHaven(id, { type, res, outDir }) {
	const [files, info] = await Promise.all([getJson(`${POLY_HAVEN}/files/${id}`), getJson(`${POLY_HAVEN}/info/${id}`)]);
	let main;
	if (type === "models") {
		const entry = files.gltf?.[res]?.gltf;
		if (!entry) throw new Error(`No glTF at ${res}. Available: ${Object.keys(files.gltf ?? {}).join(", ")}`);
		const folder = join(outDir, id);
		main = join(folder, entry.url.split("/").pop());
		await download(entry.url, main);
		for (const [relative, include] of Object.entries(entry.include ?? {})) await download(include.url, join(folder, relative));
	} else if (type === "hdris") {
		const entry = files.hdri?.[res]?.hdr;
		if (!entry) throw new Error(`No HDR at ${res}. Available: ${Object.keys(files.hdri ?? {}).join(", ")}`);
		main = join(outDir, entry.url.split("/").pop());
		await download(entry.url, main);
	} else {
		const folder = join(outDir, id);
		for (const [map, resolutions] of Object.entries(files)) {
			const entry = resolutions?.[res]?.jpg ?? resolutions?.[res]?.png;
			if (!entry || map === "blend" || map === "gltf" || map === "mtlx") continue;
			const path = join(folder, entry.url.split("/").pop());
			await download(entry.url, path);
			main ??= path;
		}
		if (!main) throw new Error(`No texture maps at ${res}.`);
	}
	recordCredit(outDir, {
		name: info.name,
		file: main.slice(outDir.length + 1),
		source: "Poly Haven",
		url: `https://polyhaven.com/a/${id}`,
		author: Object.keys(info.authors ?? {}).join(", ") || "Poly Haven",
		license: "CC0 1.0",
		licenseUrl: "https://creativecommons.org/publicdomain/zero/1.0/",
		attributionRequired: false,
	});
	return main;
}

/**
 * Downloads a Sketchfab model as GLB with its license and records the credit.
 * @param {string} uid
 * @param {{ outDir: string }} options
 * @returns {Promise<string>} main file path
 */
async function downloadSketchfab(uid, { outDir }) {
	const token = process.env.SKETCHFAB_TOKEN;
	if (!token) throw new Error("Set SKETCHFAB_TOKEN (sketchfab.com > Settings > Password & API) to download; search works without it.");
	const model = await getJson(`${SKETCHFAB}/models/${uid}`);
	const links = await getJson(`${SKETCHFAB}/models/${uid}/download`, { authorization: `Token ${token}` });
	const glb = links.glb ?? null;
	const archive = glb ?? links.gltf;
	if (!archive) throw new Error(`No glb or gltf download offered. Formats: ${Object.keys(links).join(", ")}`);
	const safe = model.name.replace(/[^\w-]+/g, "_").replace(/^_|_$/g, "") || uid;
	const main = join(outDir, `${safe}${glb ? ".glb" : ".zip"}`);
	await download(archive.url, main);
	const license = model.license ?? {};
	recordCredit(outDir, {
		name: model.name,
		file: main.slice(outDir.length + 1),
		source: "Sketchfab",
		url: model.viewerUrl ?? `https://sketchfab.com/3d-models/${uid}`,
		author: model.user?.displayName ?? model.user?.username ?? "unknown",
		license: license.label ?? "unknown",
		licenseUrl: license.url ?? "https://sketchfab.com/licenses",
		attributionRequired: !/CC0|Public Domain/i.test(license.label ?? ""),
	});
	if (/NonCommercial|NoDerivs/i.test(license.label ?? "")) console.warn(`License "${license.label}": not for commercial use, or no modifications (optimizing counts as modifying). Check before shipping.`);
	if (!glb) console.warn("Only a glTF zip was offered: unzip it, then run threejs-model-inspect on the .gltf.");
	return main;
}

/**
 * Parses arguments and runs a search or download.
 * @param {string[]} argv
 * @returns {Promise<number>}
 */
async function main(argv) {
	const args = argv.slice(2);
	const value = (flag) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : undefined);
	const takesValue = new Set(["--type", "--res", "--out", "--license", "--max-faces"]);
	const positional = args.filter((arg, index) => !arg.startsWith("--") && !takesValue.has(args[index - 1]));
	const [command, source, ...rest] = positional;
	const type = value("--type") ?? "models";
	if (!["search", "download"].includes(command) || !["polyhaven", "sketchfab"].includes(source) || rest.length === 0 || !TYPES[type]) {
		console.log("Usage:\n  node fetch.mjs search polyhaven|sketchfab <query> [--type models|hdris|textures] [--license cc0|by] [--max-faces N]\n  node fetch.mjs download polyhaven|sketchfab <id> [--type ...] [--res 1k|2k|4k] [--out dir]");
		return 1;
	}
	try {
		if (command === "search") {
			const results = source === "polyhaven" ? await searchPolyHaven(rest.join(" "), type) : await searchSketchfab(rest.join(" "), { license: value("--license"), maxFaces: Number(value("--max-faces")) || undefined });
			if (results.length === 0) console.log("No results.");
			for (const result of results) console.log(`${result.id.padEnd(34)} ${result.name}  (${result.detail})`);
			return 0;
		}
		const outDir = resolve(value("--out") ?? "assets");
		const file = source === "polyhaven" ? await downloadPolyHaven(rest[0], { type, res: value("--res") ?? "1k", outDir }) : await downloadSketchfab(rest[0], { outDir });
		console.log(`Downloaded ${file}\nCredits: ${join(outDir, "CREDITS.md")}`);
		return 0;
	} catch (error) {
		console.error(error.message);
		return 1;
	}
}

// Compare real paths so the script also runs when invoked through a symlinked skill directory.
if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
	process.exitCode = await main(process.argv);
}
